/** Stage 0: a patted-down mound with the seeds showing. Not outlined: it is part of the soil. */
function seedStage(seed: string): string[] {
  return [
    ...Array.from({ length: 10 }, () => '................'),
    '......d..d......',
    `.....dS${seed}SS${seed}d....`,
    `....dSs${seed}ss${seed}Sd...`,
    '.....dddddd.....',
    '................',
    '................',
  ];
}

function cropStages(id: CropId): SpriteDef[] {
  const art = ART[id];
  const ready = outlined(art.ready);
  const sprout = art.form === 'stalk' ? SPROUT.blade : SPROUT.leaf;
  const stage = (n: number, frames: string[][], frameMs?: number): SpriteDef => ({
    id: `crop_${id}_${n}`,
    anchor: 'bottom-center',
    frames,
    ...(frameMs ? { frameMs } : {}),
  });
  return [
    stage(0, [seedStage(art.seed)]),
    stage(1, [outlined(sprout)]),
    stage(2, [outlined(MID[art.form])]),
    stage(3, [recolored(ready, art.unripe)]),
    stage(4, [ready, sparkled(ready)], 400),
  ];
}

