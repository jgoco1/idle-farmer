// Crop sprites (ART_STYLE.md §2): `crop_<id>_<stage>` for stages 0–4, drawn over the soil tile with
// a transparent background, plus `crop_dead` for every withered crop.
//
// Authoring: the ready stage (4) of each crop is a hand-drawn fill that `outlined()` rings in
// `outline`. Stage 3 (near-ready) is the ready sprite with its produce recoloured: fruit is still
// green, roots are still soil mounds. Stages 0–2 come from a few shared shapes per plant form.
// Ready crops get a second frame with a sparkle (2 frames, 400 ms).

