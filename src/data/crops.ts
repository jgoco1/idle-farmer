import type { CropId } from './ids';
import type { CropDef } from './types';

type CropRow = Omit<CropDef, 'id' | 'stages' | 'regrowToStage' | 'unlock'> & { farmLevel: number };

function crop(id: CropId, row: CropRow): CropDef {
  const { farmLevel, ...rest } = row;
  return Object.freeze({
    id,
    ...rest,
    stages: 5,
    regrowToStage: row.regrowSec === null ? null : 2,
    unlock: Object.freeze([{ kind: 'farmLevel', level: farmLevel }] as const),
  });
}

